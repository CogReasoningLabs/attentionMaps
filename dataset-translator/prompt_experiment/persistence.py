"""Small local JSON store for prompt templates and translation experiments."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

DATA_DIR = Path(__file__).resolve().parent / "data"
PROMPTS_FILE = DATA_DIR / "prompts.json"
EXPERIMENTS_FILE = DATA_DIR / "experiments.json"
EXPERIMENTS_DIR = DATA_DIR / "experiments"
CONFIGURATIONS_FILE = DATA_DIR / "experiment_configurations.json"


def _read_list(path: Path) -> list[dict[str, Any]]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, list) else []
    except (FileNotFoundError, json.JSONDecodeError):
        return []


def _write_list(path: Path, data: list[dict[str, Any]]) -> None:
    DATA_DIR.mkdir(exist_ok=True)
    temporary_path = path.with_suffix(".tmp")
    temporary_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    temporary_path.replace(path)


def load_prompts() -> list[dict[str, Any]]:
    return _read_list(PROMPTS_FILE)


def save_prompts(prompts: list[dict[str, Any]]) -> None:
    _write_list(PROMPTS_FILE, prompts)


def load_experiments() -> list[dict[str, Any]]:
    return _read_list(EXPERIMENTS_FILE)


def save_experiments(experiments: list[dict[str, Any]]) -> None:
    _write_list(EXPERIMENTS_FILE, experiments)
    _write_experiment_files(experiments)


def _write_experiment_files(runs: list[dict[str, Any]]) -> None:
    """Write one complete, standalone artifact for every experiment launch."""
    grouped_runs: dict[str, list[dict[str, Any]]] = {}
    for run in runs:
        experiment_id = str(run.get("experiment_id") or "legacy-import")
        grouped_runs.setdefault(experiment_id, []).append(run)

    EXPERIMENTS_DIR.mkdir(parents=True, exist_ok=True)
    for experiment_id, experiment_runs in grouped_runs.items():
        first_run = experiment_runs[0]
        payload = {
            "schema_version": 1,
            "experiment_id": experiment_id,
            "experiment_label": first_run.get("experiment_label", first_run.get("experiment_name", "Legacy import")),
            "experiment_type": first_run.get("experiment_type", "legacy"),
            "created_at": first_run.get("experiment_created_at", first_run.get("created_at")),
            "dataset": first_run.get("dataset", "GAIR/lima"),
            "sample_seed": first_run.get("sample_seed"),
            "runs": experiment_runs,
        }
        # IDs are generated by the app, but keep filenames safe if an older file
        # or an externally imported record contains punctuation.
        safe_id = "".join(char if char.isalnum() or char in "-_" else "_" for char in experiment_id)
        path = EXPERIMENTS_DIR / f"{safe_id}.json"
        temporary_path = path.with_suffix(".tmp")
        temporary_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
        temporary_path.replace(path)


def load_configurations() -> list[dict[str, Any]]:
    return _read_list(CONFIGURATIONS_FILE)


def save_configurations(configurations: list[dict[str, Any]]) -> None:
    _write_list(CONFIGURATIONS_FILE, configurations)
